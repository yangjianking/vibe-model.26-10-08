// =============================================================================
//  精度与浮点类型别名（P3 混合精度抽象）
// =============================================================================
//  依据提示词 P3 第 4 条，定义三级类型别名：
//    - Real        通用计算精度（主体内核，mixed 模式下为 fp32）
//    - ComputeReal 高性能归约/求解器精度（恒 fp64，保证迭代稳健）
//    - StateReal   状态量与网格几何精度（恒 fp64，保证位可重复与守恒）
//
//  参考文献：
//    Váňa et al. (2017), Mon. Wea. Rev. 145, 4957–4970（单精度预报评估）
//    Düben & Palmer (2014), Mon. Wea. Rev. 142, 3809–3826（不精确硬件基准）
//    Chantry et al. (2019), Mon. Wea. Rev. 147（尺度选择性精度）
// =============================================================================

#pragma once

#include <cstdint>
#include <cmath>
#include <type_traits>

namespace cubed_sph {

// ---------------------------------------------------------------------------
// 精度级别
// ---------------------------------------------------------------------------
//  - 默认（fp64）：全部类型均为 double，位可重复。
//  - mixed：Real=float 用于平流/物理倾向等主体计算；StateReal/ComputeReal
//    仍为 double，用于状态累积、网格几何、椭圆求解器、全局守恒诊断。
// ---------------------------------------------------------------------------
#if defined(CS_PRECISION_MIXED)
    using Real        = float;   // 主体内核计算精度
#else
    using Real        = double;  // 默认全精度
#endif

using ComputeReal = double;      // 求解器 / 归约 / 迭代精化恒 fp64
using StateReal   = double;      // 状态量 / 网格几何 / 守恒诊断恒 fp64

// 整数索引类型：面板内 2D 索引 (i,j) 与全局扁平索引
// 注意：命名避免使用 "Index"，因其与 Windows SDK 头文件冲突（跨平台健壮性）。
using Idx    = std::int32_t;    // 面板内索引
using IIndex = std::int64_t;    // 大网格下的全局索引（可跨 32 位边界）

// ---------------------------------------------------------------------------
// 数值常量与安全函数
// ---------------------------------------------------------------------------
constexpr ComputeReal kPi = 3.141592653589793238462643383279502884;

// 三维/二维索引结构（面板局部笛卡尔索引，不含 halo 偏移时即为物理点）
struct Index2 {
    Idx i = 0;
    Idx j = 0;
};

struct Index3 {
    Idx i = 0;
    Idx j = 0;
    Idx k = 0;
};

}  // namespace cubed_sph
