// =============================================================================
//  面板间向量旋转（Panel-to-Panel Vector Rotation）
// =============================================================================
//  跨面板 halo 交换时，向量场（协变/反变分量）需从源面板局部基旋转到
//  目标面板局部基。旋转矩阵仅依赖两个面板的相对朝向，与网格点位置无关
//  （这是采用 gnomonic 投影 + 协变分量的重要优势）。
//
//  旋转公式：设源面板局部正交基 (e1, e2, n)，目标面板基 (f1, f2, n')，
//  切平面向量 v = v1 e1 + v2 e2 在目标基下的分量为：
//    v1' = v·f1 = v1 (e1·f1) + v2 (e2·f1)
//    v2' = v·f2 = v1 (e1·f2) + v2 (e2·f2)
//  旋转矩阵 R 的 4 个元素即两基向量内积，可离线预计算并缓存。
//
//  参考文献：
//    Putman & Lin (2007), J. Comput. Phys. 227, 55–78（面板旋转）
//    Harris et al. (2021), GFDL TM GFDL2021001 §3.2（FV³ 面板交换）
// =============================================================================

#pragma once

#include "cubed_sph/grid/panel.hpp"

namespace cubed_sph::grid {

// ---------------------------------------------------------------------------
// 2x2 面板旋转矩阵（切平面内）
// ---------------------------------------------------------------------------
struct PanelRotation {
    // 元素按 (e1·f1, e2·f1; e1·f2, e2·f2) 排列
    StateReal r11 = 1.0;
    StateReal r12 = 0.0;
    StateReal r21 = 0.0;
    StateReal r22 = 1.0;
};

// 返回从面板 src 旋转到面板 dst 的切向旋转矩阵
//（在 panel_rotation.cpp 中基于面板朝向离线构造）
PanelRotation panel_rotation(PanelId src, PanelId dst);

// ---------------------------------------------------------------------------
// 应用旋转：把源面板切向分量 (u,v) 旋转到目标面板
// ---------------------------------------------------------------------------
inline void rotate_uv(const PanelRotation& R,
                      StateReal u, StateReal v,
                      StateReal& u_out, StateReal& v_out) {
    u_out = R.r11 * u + R.r12 * v;
    v_out = R.r21 * u + R.r22 * v;
}

}  // namespace cubed_sph::grid
